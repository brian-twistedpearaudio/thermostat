#!/usr/bin/env python3
"""Generate the LVGL 9 fonts used by the home screen from Montserrat.

Run from the firmware folder:  python3 fonts/make_fonts.py
Needs freetype-py (pip install freetype-py). Writes src/fonts/*.c and src/fonts/ui_fonts.h.

Sizes are the design canvas sizes halved (the canvas is drawn at 2x of the 320x170 screen).
"""
import math
import os
import freetype

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, "Montserrat-VariableWeight.ttf")
OUT = os.path.join(HERE, "..", "src", "fonts")

ASCII = [chr(c) for c in range(0x20, 0x7F)]
DIGITS = list("0123456789")

# name, weight, pixel size, characters
FONTS = [
    ("ui_font_temp_75", 600, 75, DIGITS + ["-"]),                  # inside temperature, whole part
    ("ui_font_temp_60", 600, 60, DIGITS + ["-"]),                  # idle screen temperature
    ("ui_font_frac_32", 600, 32, DIGITS + ["-", ".", "°"]),   # ".4°"
    ("ui_font_set_26", 700, 26, DIGITS + ["-", "°"]),         # set point
    ("ui_font_body_11", 500, 11, ASCII + ["°", "·"]),    # Inside, clock, humidity
    ("ui_font_semi_11", 600, 11, ASCII + ["°", "·"]),    # status pills
    ("ui_font_caption_9", 600, 9, ASCII),                          # SET / MANUAL caption
]


def render(name, weight, size, chars):
    face = freetype.Face(TTF)
    face.set_var_design_coords((weight,))
    face.set_pixel_sizes(0, size)
    upem = face.units_per_EM
    asc = face.ascender * size / upem
    desc = -face.descender * size / upem
    small = size <= 14
    flags = freetype.FT_LOAD_RENDER | (freetype.FT_LOAD_TARGET_LIGHT if small else freetype.FT_LOAD_NO_HINTING)

    cps = sorted(set(ord(c) for c in chars))
    bitmap_bytes = []
    dscs = []
    cap_h = x_h = 0
    for cp in cps:
        face.load_char(chr(cp), flags)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        px = []
        for y in range(h):
            row = bm.buffer[y * bm.pitch: y * bm.pitch + w]
            px.extend((v * 15 + 127) // 255 for v in row)
        if len(px) % 2:
            px.append(0)
        start = len(bitmap_bytes)
        for i in range(0, len(px), 2):
            bitmap_bytes.append((px[i] << 4) | px[i + 1])
        adv = int(round(g.advance.x / 64 * 16))
        ofs_y = g.bitmap_top - h
        dscs.append((start, adv, w, h, g.bitmap_left, ofs_y, cp))
        if chr(cp) == "H":
            cap_h = g.bitmap_top
        if chr(cp) == "x":
            x_h = g.bitmap_top
        if chr(cp) == "0" and not cap_h:
            cap_h = g.bitmap_top

    line_height = int(math.ceil(asc + desc))
    base_line = int(math.ceil(desc))

    lines = []
    lines.append("// Generated by fonts/make_fonts.py from Montserrat (SIL Open Font License, see fonts/OFL.txt).")
    lines.append(f"// Weight {weight}, {size} px, 4 bpp, {len(cps)} glyphs. Do not edit by hand.")
    lines.append('#include <lvgl.h>\n')
    lines.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap_bytes), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap_bytes[i:i + 16]) + ",")
    if not bitmap_bytes:
        lines.append("    0x00,")
    lines.append("};\n")
    lines.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    lines.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for (start, adv, w, h, ox, oy, cp) in dscs:
        lines.append(f"    {{.bitmap_index = {start}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
                     f".ofs_x = {ox}, .ofs_y = {oy}}},  /* U+{cp:04X} */")
    lines.append("};\n")
    first = cps[0]
    lines.append("static const uint16_t unicode_list[] = {")
    lines.append("    " + ", ".join(f"0x{cp - first:x}" for cp in cps))
    lines.append("};\n")
    lines.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    lines.append(f"    {{.range_start = {first}, .range_length = {cps[-1] - first + 1}, .glyph_id_start = 1,")
    lines.append(f"     .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(cps)},")
    lines.append("     .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY},")
    lines.append("};\n")
    lines.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    lines.append("    .glyph_bitmap = glyph_bitmap,")
    lines.append("    .glyph_dsc = glyph_dsc,")
    lines.append("    .cmaps = cmaps,")
    lines.append("    .kern_dsc = NULL,")
    lines.append("    .kern_scale = 0,")
    lines.append("    .cmap_num = 1,")
    lines.append("    .bpp = 4,")
    lines.append("    .kern_classes = 0,")
    lines.append("    .bitmap_format = 0,")
    lines.append("};\n")
    lines.append(f"const lv_font_t {name} = {{")
    lines.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    lines.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    lines.append(f"    .line_height = {line_height},")
    lines.append(f"    .base_line = {base_line},")
    lines.append("#if LV_VERSION_CHECK(9, 6, 0) || LVGL_VERSION_MAJOR >= 10")
    lines.append(f"    .cap_height = {cap_h},")
    lines.append(f"    .x_height = {x_h},")
    lines.append("#endif")
    lines.append("    .subpx = LV_FONT_SUBPX_NONE,")
    lines.append(f"    .underline_position = {-max(1, round(size * 0.1))},")
    lines.append(f"    .underline_thickness = {max(1, round(size * 0.07))},")
    lines.append("#if LV_VERSION_CHECK(9, 3, 0)")
    lines.append("    .static_bitmap = 1,")
    lines.append("#endif")
    lines.append("    .dsc = &font_dsc,")
    lines.append("    .fallback = NULL,")
    lines.append("    .user_data = NULL,")
    lines.append("};")
    with open(os.path.join(OUT, name + ".c"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return line_height, base_line, asc, desc


def text_width(weight, size, text):
    face = freetype.Face(TTF)
    face.set_var_design_coords((weight,))
    face.set_pixel_sizes(0, size)
    w = 0
    for ch in text:
        face.load_char(ch, freetype.FT_LOAD_TARGET_LIGHT)
        w += face.glyph.advance.x / 64
    return w


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    hdr = ["// Generated by fonts/make_fonts.py. Do not edit by hand.", "#pragma once", "#include <lvgl.h>", "",
           "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    for name, weight, size, chars in FONTS:
        lh, bl, asc, desc = render(name, weight, size, chars)
        print(f"{name}: line_height {lh}, base_line {bl}, ascent {asc:.2f}, descent {desc:.2f}")
        hdr.append(f"LV_FONT_DECLARE({name})  // Montserrat {weight}, {size} px")
    hdr += ["", "#ifdef __cplusplus", "}", "#endif"]
    with open(os.path.join(OUT, "ui_fonts.h"), "w", newline="\n") as f:
        f.write("\n".join(hdr) + "\n")
    for t in ("Sensor fault · heat is off", "Sensor fault · heat off", "41% humidity", "Heating"):
        print(f"width @11/600 {t!r}: {text_width(600, 11, t):.1f}")
